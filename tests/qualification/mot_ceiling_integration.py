#!/usr/bin/env python3
"""Cross-check MOT ceiling derivation against real NASM fixtures."""

import importlib.util
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ENGINE = ROOT / "qualification/tools/effective_limit_engine.py"
HEADER = ROOT / "include/asmweb/registry.inc"
ASSEMBLY_TEST = ROOT / "tests/qualification/memory_ceiling.asm"

spec = importlib.util.spec_from_file_location("mot_engine", ENGINE)
engine = importlib.util.module_from_spec(spec)
spec.loader.exec_module(engine)

class Failure(Exception):
    pass

def check(ok, message):
    if not ok:
        raise Failure(message)

def load_module_fixture(name):
    text = ASSEMBLY_TEST.read_text(encoding="utf-8")

    match = re.search(
        rf"(?m)^{re.escape(name)}:\s*\n",
        text,
    )
    check(match is not None, f"fixture missing: {name}")

    tail = text[match.end():]

    # Stop at next assembly label, or a section directive.
    end = re.search(
        r"(?m)^(?:[A-Za-z_][A-Za-z_0-9]*:|section\s+)",
        tail,
    )
    body = tail[:end.start()] if end else tail

    tokens = re.findall(
        r"(?m)^\s*dq\s+([^;\n]+)",
        body,
    )

    values = []
    lifecycle = {
        "ASMWEB_REGISTRY_STATUS_ACTIVE": engine.MOT_ACTIVE,
        "ASMWEB_REGISTRY_STATUS_DEFERRED": engine.MOT_DEFERRED,
        "ASMWEB_REGISTRY_STATUS_SUPERSEDED": engine.MOT_SUPERSEDED,
        "ASMWEB_REGISTRY_STATUS_RETIRED": engine.MOT_RETIRED,
    }

    for token in tokens:
        token = token.strip()
        value = (
            lifecycle[token]
            if token in lifecycle
            else int(token, 0)
        )
        values.append(value)

    check(
        len(values) > 0
        and len(values) % len(engine.MOT_FIELDS) == 0,
        f"unexpected MOT fixture width: {name}",
    )

    entries = []

    for index in range(0, len(values), len(engine.MOT_FIELDS)):
        part = values[index:index + len(engine.MOT_FIELDS)]
        entries.append(dict(zip(engine.MOT_FIELDS, part)))

    return {"schema_version": 1, "entries": entries}

def to_bytes(document):
    return json.dumps(document).encode("utf-8")

def reject(name, document):
    try:
        engine.calculate_mot_ceiling_bytes(to_bytes(document))
    except engine.LimitError:
        print(f"{name}=REJECTED")
        return
    raise Failure(f"{name}: incorrectly accepted")

try:
    header = HEADER.read_text(encoding="utf-8")
    source = (
        ROOT / "src/runtime/memory_ceiling.asm"
    ).read_text(encoding="utf-8")

    # Guard the descriptor interpretation against source evolution.
    declaration = re.search(
        r"struc ASMWEB_MOT_VALIDATION_ENTRY(.*?)endstruc",
        header,
        re.S,
    )
    check(declaration is not None, "MOT descriptor missing")

    actual_fields = tuple(re.findall(
        r"(?m)^\s*\.([a-z_]+):\s+resq\s+1\s*$",
        declaration.group(1),
    ))
    check(
        actual_fields == engine.MOT_FIELDS,
        "MOT descriptor layout disagreement",
    )

    for name, value in (
        ("ACTIVE", engine.MOT_ACTIVE),
        ("DEFERRED", engine.MOT_DEFERRED),
        ("SUPERSEDED", engine.MOT_SUPERSEDED),
        ("RETIRED", engine.MOT_RETIRED),
    ):
        check(
            re.search(
                rf"(?m)^%define\s+ASMWEB_REGISTRY_STATUS_{name}"
                rf"\s+{value}\s*$",
                header,
            ) is not None,
            f"lifecycle definition mismatch: {name}",
        )

    check(
        re.search(
            r"(?m)^%define\s+ASMWEB_M0_MAX_MOT_ENTRIES\s+256\s*$",
            header,
        ) is not None,
        "MOT count bound mismatch",
    )

    for required in (
        "asm_memory_direct_capacity_from_mot:",
        "ASMWEB_MOT_VALIDATION_ENTRY.maximum_count",
        "ASMWEB_MOT_VALIDATION_ENTRY.status",
        "ASMWEB_MOT_VALIDATION_ENTRY.pool_metadata_bytes",
        "ASMWEB_MOT_VALIDATION_ENTRY.mapping_overhead_bytes",
        "asm_memory_fixed_class_capacity",
        "asm_u64_add_checked",
    ):
        check(required in source, "missing assembly operand: " + required)

    print("MOT_DESCRIPTOR_ALIGNMENT=PASS")
    print("MOT_LIFECYCLE_ALIGNMENT=PASS")

    # Expected numbers are independently recorded in the existing
    # executable assembly qualification, not generated by this engine.
    fixtures = (
        ("mot_one_active", 4768),
        ("mot_mixed", 9136),
        ("mot_all_inactive", 0),
        ("mot_exact_max", engine.U64_MAX),
    )

    for name, expected in fixtures:
        document = load_module_fixture(name)
        result = engine.calculate_mot_ceiling_bytes(
            to_bytes(document)
        )
        check(
            result["M_direct_capacity_max"] == expected,
            f"assembly oracle mismatch: {name}",
        )
        check(
            result["authoritative_manifest"] is False,
            f"false authority: {name}",
        )
        print(f"{name}=PASS ceiling={expected}")

    for name in (
        "mot_class_overflow",
        "mot_aggregate_overflow",
        "mot_invalid_status",
    ):
        reject(name, load_module_fixture(name))

    # The runtime's arithmetic layer accepts an empty MOT.
    empty = {"schema_version": 1, "entries": []}
    check(
        engine.calculate_mot_ceiling(empty)["M_direct_capacity_max"] == 0,
        "empty MOT",
    )
    print("canonical_empty_mot=PASS")

    # Inactive entries with extreme unused operands are ignored.
    mixed = load_module_fixture("mot_mixed")
    reordered = {
        "schema_version": 1,
        "entries": list(reversed(mixed["entries"])),
    }
    check(
        engine.canonical(engine.calculate_mot_ceiling(mixed))
        == engine.canonical(engine.calculate_mot_ceiling(reordered)),
        "order dependence",
    )
    print("canonical_order=PASS")

    changed = load_module_fixture("mot_one_active")
    changed["entries"][0]["configured_capacity"] = 1
    result = engine.calculate_mot_ceiling(changed)
    check(
        result["M_direct_capacity_max"] == 4768,
        "ceiling incorrectly uses configured capacity",
    )
    print("maximum_count_not_configured=PASS")

    duplicate = load_module_fixture("mot_one_active")
    duplicate["entries"].append(dict(duplicate["entries"][0]))
    reject("duplicate_limit_id", duplicate)

    zero_id = load_module_fixture("mot_one_active")
    zero_id["entries"][0]["limit_id"] = 0
    reject("zero_limit_id", zero_id)

    oversized = {
        "schema_version": 1,
        "entries": (
            [dict(load_module_fixture("mot_one_active")["entries"][0])]
            * 257
        ),
    }
    reject("entry_count_bound", oversized)

    for name, payload in (
        ("duplicate_json_key",
         b'{"schema_version":1,"schema_version":1,"entries":[]}'),
        ("invalid_utf8",
         b'{"schema_version":1,"entries":[]}\xff'),
        ("trailing_document",
         b'{"schema_version":1,"entries":[]}{}'),
        ("nonfinite",
         b'{"schema_version":1,"entries":NaN}'),
    ):
        # Interpret the explicitly written escape for invalid UTF-8.
        if name == "invalid_utf8":
            payload = payload.replace(b"\\\\xff", bytes([255]))
        try:
            engine.calculate_mot_ceiling_bytes(payload)
        except engine.LimitError:
            print(f"{name}=REJECTED")
        else:
            raise Failure(name + ": incorrectly accepted")

    print("ASSEMBLY_MOT_FIXTURE_ALIGNMENT=PASS")
    print("MOT_CEILING_INTEGRATION=PASS")
    print("AUTHORITATIVE_MANIFEST=False")
    print("M0_BLOCK_LR=OPEN")
    print("M0_BLOCK_ELM=OPEN")

except (Failure, OSError, ValueError, KeyError,
        TypeError, engine.LimitError) as exc:
    print(f"MOT_CEILING_INTEGRATION=FAIL: {exc}")
    sys.exit(1)
